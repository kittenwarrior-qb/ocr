def find_template(
    db: Session,
    tax_code: str | None,
    document_type: str | None,
    format_hint: str | None = None,
    order_number: str | None = None,
) -> Template | None:
    # Ưu tiên 1: template gắn partner qua MST
    if tax_code and document_type:
        mst = db.query(MSTMapping).filter(MSTMapping.tax_code == tax_code).first()
        if mst:
            template = (
                db.query(Template)
                .filter(
                    Template.partner_id == mst.partner_id,
                    Template.document_type == document_type,
                    Template.is_active,
                )
                .first()
            )
            if template:
                return template

    # Ưu tiên 2: template theo tiền tố mã PO (_po_prefix)
    if order_number and document_type:
        candidates = (
            db.query(Template)
            .filter(
                Template.document_type == document_type,
                Template.is_active == True,
                Template.field_aliases.isnot(None),
            )
            .all()
        )
        for t in candidates:
            prefixes = (t.field_aliases or {}).get("_po_prefix", [])
            if any(order_number.startswith(p) for p in prefixes if p):
                return t

    # Ưu tiên 3: built-in template theo format_hint từ pass 1
    if format_hint and format_hint != "standard":
        code = _FORMAT_HINT_TO_TEMPLATE.get(format_hint)
        if code:
            t = db.query(Template).filter(Template.code == code, Template.is_active == True).first()
            if t:
                return t

    return None


def get_generic_template_prompt() -> str:
    return GENERIC_FULL_PROMPT


def create_template(
    db: Session,
    partner_id,
    document_type: str,
    name: str,
    system_prompt: str,
    output_schema: dict,
    field_aliases: dict | None = None,
) -> Template:
    code = generate_template_code(db)
    template = Template(
        code=code,
        partner_id=partner_id,
        document_type=document_type,
        name=name,
        system_prompt=system_prompt,
        output_schema=output_schema,
        field_aliases=field_aliases or {},
    )
    db.add(template)
    db.commit()
    db.refresh(template)
    return template


