def build_system_prompt_from_schema(output_schema: dict) -> str:
    import json
    schema_str = json.dumps(output_schema, ensure_ascii=False, indent=2)
    return (
        "You are an expert at extracting structured data from Vietnamese business documents "
        "(purchase orders and VAT invoices). "
        "Extract all fields and return valid JSON only (no markdown).\n"
        f"Required output schema:\n{schema_str}\n"
        "For missing fields use null. Items must be an array."
    )


def seed_builtin_templates(db: Session) -> None:
    """Tạo sẵn các template cho format đặc biệt nếu chưa tồn tại."""
    for tpl in _BUILTIN_TEMPLATES:
        exists = db.query(Template).filter(Template.code == tpl["code"]).first()
        if not exists:
            db.add(Template(
                code=tpl["code"],
                partner_id=None,
                document_type=tpl["document_type"],
                name=tpl["name"],
                system_prompt=tpl["system_prompt"],
                output_schema=tpl["output_schema"],
                field_aliases=tpl.get("field_aliases", {}),
                is_active=True,
            ))
    db.commit()


def build_prompt_with_aliases(field_aliases: dict) -> str:
    """Sinh OCR prompt từ GENERIC_FULL_PROMPT + alias mapping của user.

    field_aliases = {"payment_method": ["HTTT", "P.thức TT"], "recipient_name": ["NNH"]}
    Keys bắt đầu bằng '_' (như _po_prefix) là metadata nội bộ, không đưa vào prompt.
    """
    if not field_aliases:
        return GENERIC_FULL_PROMPT

    alias_lines = []
    for field, aliases in field_aliases.items():
        if field.startswith("_") or not aliases:
            continue
        label_vi = _FIELD_LABELS_VI.get(field, field)
        alias_quoted = ", ".join(f'"{a}"' for a in aliases)
        alias_lines.append(f'- {label_vi} ("{field}"): label trên chứng từ có thể là {alias_quoted}')

    if not alias_lines:
        return GENERIC_FULL_PROMPT

    alias_block = "\n".join(alias_lines)
    return (
        f"{GENERIC_FULL_PROMPT}\n\n"
        "QUAN TRỌNG — Alias mapping riêng cho chứng từ này:\n"
        f"{alias_block}\n\n"
        "Khi tìm giá trị, hãy nhận diện cả các label thay thế được liệt kê ở trên."
    )
